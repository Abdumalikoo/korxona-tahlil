import prismaPkg from '@prisma/client';
const { PrismaClient } = prismaPkg;
const prisma = new PrismaClient();
const TZ = 5 * 3600_000;
const today = new Date(Date.now() + TZ).toISOString().slice(0, 10);
const year = today.slice(0, 4);
const start = new Date(Date.parse(`${year}-01-01`) - TZ);
const end = new Date(Date.parse(today) + 86400_000 - TZ);
const curMonth = today.slice(0, 7);
const lastMonth = (() => { const [y, m] = curMonth.split('-').map(Number); const i = y * 12 + m - 2; return `${Math.floor(i / 12)}-${String((i % 12) + 1).padStart(2, '0')}`; })();
const mlrd = (t) => (Number(t ?? 0) / 100 / 1e9).toFixed(3).replace('.', ',') + ' mlrd';
const sum = async (model, where, field = 'amountTiyin') => (await model.aggregate({ where: { deletedAt: null, ...where }, _sum: { [field]: true } }))._sum[field] ?? 0n;
const row = async (name, incWhere, expWhere, incField) => {
  const inc = await sum(prisma.income, incWhere, incField);
  const exp = await sum(prisma.expense, expWhere);
  console.log(`${name.padEnd(58)} daromad ${mlrd(inc).padStart(14)} | xarajat ${mlrd(exp).padStart(14)} | natija ${mlrd(inc - exp).padStart(14)}`);
};
const byDate = { date: { gte: start, lt: end } };
const byPeriod = (to) => ({ period: { gte: `${year}-01`, lte: to } });
console.log(`Bugun: ${today}\n`);
await row(`1) Sana bo'yicha ${year}-01-01 — ${today} (Solishtirma)`, byDate, byDate);
await row(`2) Oy bo'yicha ${year}-01 — ${curMonth}`, byPeriod(curMonth), byPeriod(curMonth));
await row(`3) Oy bo'yicha ${year}-01 — ${lastMonth} (tugagan oylar)`, byPeriod(lastMonth), byPeriod(lastMonth));
await row('4) Sana bo\'yicha, daromad — to\'langan summa (paid)', byDate, byDate, 'paidTiyin');
await row('5) Sana bo\'yicha, faqat DOIMIY', { ...byDate, section: 'DOIMIY' }, { ...byDate, section: 'DOIMIY' });
await row(`6) Faqat joriy oy (${curMonth})`, { period: curMonth }, { period: curMonth });
const edge = await prisma.expense.aggregate({ where: { deletedAt: null, ...byDate, NOT: { period: { gte: `${year}-01`, lte: curMonth } } }, _sum: { amountTiyin: true }, _count: { _all: true } });
console.log(`\nSanasi davr ichida, lekin oyi boshqa bo'lgan xarajatlar: ${edge._count._all} ta, ${mlrd(edge._sum.amountTiyin)}`);
await prisma.$disconnect();